// Run: npx tsx scripts/route/buildMarrakech.ts
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { planMarrakech } from '../../packages/shared/src/courses/marrakech.plan';
import type { SegmentDef } from '../../packages/shared/src/segments';

const { segments, report, placements, inserted } = planMarrakech();

const field = (key: string, value: unknown): string => `${key}: ${typeof value === 'string' ? `'${value}'` : JSON.stringify(value)}`;
const line = (def: SegmentDef): string => `  { ${Object.entries(def).map(([key, value]) => field(key, value)).join(', ')} },`;
const text = [
  '// Generated by scripts/route/buildMarrakech.ts from marrakech.route.ts. Do not edit by hand.',
  "import type { SegmentDef } from '../segments';",
  '',
  'export const MARRAKECH_SEGMENTS: SegmentDef[] = [',
  ...segments.map(line),
  '];',
  '',
  '// Indexes of the inserted terrain (sand, alley, roadworks, ford group); stops and hazards skip them.',
  `export const MARRAKECH_INSERTED: readonly number[] = [${inserted.join(', ')}];`,
  '',
].join('\n');
writeFileSync(fileURLToPath(new URL('../../packages/shared/src/courses/marrakech.generated.ts', import.meta.url)), text);

const km = (m: number): string => `${(m / 1000).toFixed(2)} km`;
console.log(`segments (fit, before inserts): ${report.segmentCount}; after inserts: ${segments.length}`);
console.log(`total length: ${km(report.totalLength)} (real route ${km(report.realLength)}, ${(((report.totalLength - report.realLength) / report.realLength) * 100).toFixed(2)} %)`);
console.log(`largest deviation: ${report.maxDeviation.toFixed(0)} m matched by arc length, ${report.maxNearest.toFixed(0)} m to the nearest real point`);
console.log(`end-point error: ${report.endError.toFixed(1)} m`);
console.log(`largest stretch: ${report.maxStretch.toFixed(1)} m (${report.stretches} curves stretched)`);
for (const p of placements) console.log(`insert ${p.name}: target ${p.target.toFixed(0)} m, at ${p.at.toFixed(0)} m, ${p.distance.toFixed(0)} m from target`);
