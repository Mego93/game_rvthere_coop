// Run: npx tsx scripts/route/buildOurika.ts
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { planOurika } from '../../packages/shared/src/courses/ourika.plan';
import type { SegmentDef } from '../../packages/shared/src/segments';

const { segments, report } = planOurika();

const literal = (value: unknown): string => {
  if (typeof value === 'string') return `'${value}'`;
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;
  if (value && typeof value === 'object') return `{ ${Object.entries(value).map(([k, v]) => `${k}: ${literal(v)}`).join(', ')} }`;
  return JSON.stringify(value);
};
const line = (def: SegmentDef): string => `  { ${Object.entries(def).map(([key, value]) => `${key}: ${literal(value)}`).join(', ')} },`;
const text = [
  '// Generated by scripts/route/buildOurika.ts from ourika.route.ts. Do not edit by hand.',
  "import type { SegmentDef } from '../segments';",
  '',
  'export const OURIKA_SEGMENTS: SegmentDef[] = [',
  ...segments.map(line),
  '];',
  '',
].join('\n');
writeFileSync(fileURLToPath(new URL('../../packages/shared/src/courses/ourika.generated.ts', import.meta.url)), text);

console.log(`segments: ${report.segmentCount}; length ${report.total.toFixed(0)} m (real ${report.realLength.toFixed(0)} m)`);
console.log(`farthest the road strays from the real one: ${report.maxNearest.toFixed(0)} m; end error ${report.endError.toFixed(0)} m`);
console.log(`climb ${report.climb.toFixed(0)} m (net ${report.net.toFixed(0)} m)`);
console.log(`slope histogram (degrees: straights): ${Object.entries(report.histogram).sort((a, b) => Number(a[0]) - Number(b[0])).map(([k, v]) => `${k}:${v}`).join(' ')}`);
const gaps = report.fuel.map((f, i) => f.at - (i === 0 ? 0 : report.fuel[i - 1]!.at)).concat(report.total - report.fuel[report.fuel.length - 1]!.at);
console.log(`fuel stops: ${report.fuel.length}; gaps (m): ${gaps.map((g) => g.toFixed(0)).join(' ')}`);
console.log(`pickups ${report.extras.pickups.length}, coins ${report.extras.coins}, mud ${report.extras.mud.length}, rocks ${report.extras.rocks.length}, hazards ${report.extras.hazards.length}`);
